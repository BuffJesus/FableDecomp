"""Reproducible inactive Maze candidate composed with reviewed host capabilities."""
import json
import hashlib
from pathlib import Path
from lupa.lua54 import LuaRuntime
from tools.script_recovery.lift_native_lua import ROOT
from tools.script_recovery.maze_converter import convert


def compose_bodies(bodies):
    result=dict(bodies)
    edits={
        'EmptyGrave.Main':[
            ('    local sword = quest:GetThingWithScriptName("GoodSword")\n    quest:RetainRetailThing("MazeResearch", sword)\n    quest:EntitySetInLimbo(sword, true, true)',
             '    quest:InitializeMazeSword()'),
            ('quest:CreateThread("UnLimboSword", {region = ""})','quest:CreateMazeUnlimboThread()')],
        'MazeResearch.UNLIMBO':[
            ('    local sword = quest:GetRetainedRetailThing("MazeResearch")\n    quest:EntitySetInLimbo(sword, false, true)\n    quest:EntitySetAlpha(sword, 0.0, true)',
             '    quest:UnlimboMazeSword()')]}
    for key,changes in edits.items():
        for old,new in changes:
            if result[key].count(old)!=1:raise ValueError('Maze runtime composition correspondence changed: '+key)
            result[key]=result[key].replace(old,new)
    return result


def generate(output=None):
    output=Path(output or ROOT/'work/maze_converter/runtime_candidate').resolve()
    if not output.is_relative_to((ROOT/'work/maze_converter').resolve()):
        raise ValueError('Maze runtime candidate must remain under work/maze_converter')
    report=convert(output)
    # Compose over the exact checked function text already generated by the
    # native converter, so no reference-port text enters the implementation.
    paths={'EmptyGrave.Main':output/'Entities/EmptyGrave.lua','MazeResearch.UNLIMBO':output/'MazeResearch.lua'}
    texts={key:path.read_text() for key,path in paths.items()}
    composed=compose_bodies(texts)
    for key,path in paths.items():
        LuaRuntime().execute('return function()\n'+composed[key]+'\nend')
        path.write_text(composed[key])
    report['status']='disabled runtime-aware candidate; host proposals pending integration'
    report['requiredHostCapabilities']={
        'AddMiniMapMarkerByScriptName':'maze_marker_adapter.inc: atomic lookup/marker consumer and native temporary destruction order.',
        'InitializeMazeSword':'maze_sword_adapter.inc + maze_sword_slot.h: exclusive native slot, Info-identity assignment, no Lua owner.',
        'UnlimboMazeSword':'maze_sword_adapter.inc: atomic limbo/alpha consumers of the current native slot.',
        'CreateMazeUnlimboThread':'maze_entry_adapter.inc + staged host changes: opt-in native cancellation entry, explicit empty region.'}
    report['pendingCapabilities']=list(report['requiredHostCapabilities'])
    report['composedProposalBehavior']=[
        'Replaces persistent Lua Sword userdata with an exclusively owned native slot.',
        'Preserves helper first-frame cancellation behavior through opt-in host dispatch.',
        'Existing default host thread entry policy remains unchanged.']
    report['lifecycleAudit']['candidateResolution']={
        'retained-sword-lua-owner':'Addressed by staged exclusive Sword capability; current runtime still requires integration.',
        'thread-pre-entry-cancellation':'Addressed by staged opt-in helper entry capability; current runtime still requires integration.',
        'flags-and-parent-teardown':'Unresolved manager drain/removal integration gate.',
        'engine-restoration-order':'Unresolved engine restore/streaming integration gate.'}
    report['unresolvedIntegrationGate']=[
        'Manager-controlled native drain/removal must precede flags, Sword and Lua teardown on every host deletion path.',
        'Prove no future engine dispatch and complete macro/entity/helper unwind; entry callback counters alone do not establish this.',
        'Preserve native manager current-quest context; do not call raw KillAllThreads from the active parent fiber.',
        'Verify engine Init/OnPersist/entity/thread restoration and streaming ordering. Boolean field trace matches do not prove whole-save restoration.']
    report['remaining']=[
        'Install and review required host capabilities before activation.',
        *report['unresolvedIntegrationGate']]
    report['evidenceReferences']={
        'marker':'work/maze_converter/runtime_proposal/proposal.json',
        'sword':'work/maze_converter/sword_proposal/proposal.json',
        'entry':'work/maze_converter/entry_proposal/proposal.json',
        'teardown':'work/maze_converter/teardown_evidence/TEARDOWN_REPORT.json'}
    (output/'quests.lua').write_text('-- Disabled: required host proposals and manager teardown/save-restore gate remain pending.\n')
    report['generatedLuaSha256']={str(path.relative_to(output)):hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(output.rglob('*.lua'))}
    (output/'COVERAGE.json').write_text(json.dumps(report,indent=2)+'\n')
    return report


if __name__=='__main__':
    result=generate()
    print(json.dumps({key:result[key] for key in ('status','registrationEnabled','pendingCapabilities','unresolvedIntegrationGate')},indent=2))
