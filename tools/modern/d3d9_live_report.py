"""Report a live IDirect3DDevice9 trace (d3d9_live_census.py) against the static census.

Usage: python tools/modern/d3d9_live_report.py <live.json> [--label frontend]
Writes docs/modern/D3D9_LIVE_CENSUS.md and copies the trace to docs/modern/D3D9_LIVE_CENSUS_<label>.json.
Each live return address is mapped back to its call instruction and compared with the static
census's call sites (docs/modern/D3D9_DEVICE_CENSUS.json).
"""
from __future__ import annotations

import argparse
import bisect
import json
import shutil
import sys
from pathlib import Path

import capstone

sys.path.insert(0, str(Path(__file__).resolve().parent))
import d3d9_device_census as census  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT_MD = ROOT / "docs" / "modern" / "D3D9_LIVE_CENSUS.md"
STATIC = ROOT / "docs" / "modern" / "D3D9_DEVICE_CENSUS.json"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("live")
    ap.add_argument("--label", default="frontend")
    args = ap.parse_args()
    live = json.loads(Path(args.live).read_text())
    shutil.copyfile(args.live, ROOT / "docs" / "modern" / f"D3D9_LIVE_CENSUS_{args.label}.json")

    base, img = census.load_image()
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    fns = sorted(census.functions())
    starts = [f[0] for f in fns]
    image_end = base + len(img)

    def func(a):
        j = bisect.bisect_right(starts, a) - 1
        return fns[j] if j >= 0 and a < fns[j][0] + fns[j][2] else None

    def call_before(ret):
        for n in (2, 3, 5, 6, 7):
            ins = list(md.disasm(img[ret - n - base:ret - base], ret - n))
            if len(ins) == 1 and ins[0].mnemonic == "call":
                return ret - n
        return None

    static = json.loads(STATIC.read_text())
    static_calls = {int(s["call"], 16) for s in static["sites"]}
    static_methods = {s["method"] for s in static["sites"]}
    # A COM tail call (`jmp [vtbl+off]`) returns into the caller of F, right after `call F`.
    static_fn_method = {(int(s["function"], 16), s["method"]) for s in static["sites"]}

    def direct_target(c):
        ins = list(md.disasm(img[c - base:c - base + 5], c)) if c else []
        if ins and ins[0].mnemonic == "call" and ins[0].op_str.startswith("0x"):
            return int(ins[0].op_str, 16)
        return None

    matched, new, extern = [], [], []
    for meth, v in live["methods"].items():
        for r, hits in v["call_sites"].items():
            r = int(r, 16)
            if not base <= r < image_end:
                extern.append((meth, r, hits))
                continue
            c = call_before(r)
            f = func(r)
            row = (meth, c or r, f[0] if f else 0, f[1] if f else "?", hits)
            hit = c in static_calls or (direct_target(c), meth) in static_fn_method
            (matched if hit else new).append(row)

    live_methods = set(live["methods"])
    L = [
        "# D3D9 device census: live trace",
        "",
        "Generated by `tools/modern/d3d9_live_report.py` from a `d3d9_live_census.py --attach` trace. Do not",
        "edit by hand. Complements the static lower bound in [D3D9_DEVICE_CENSUS](D3D9_DEVICE_CENSUS.md).",
        "",
        f"Trace `{args.label}`: device `{live['device']}`, vtable `{live['vtable']}` (a heap copy; QI, Release,",
        "CreateAdditionalSwapChain and Reset are apphelp.dll shims). Each method's breakpoint was removed",
        f"after {live['budget']} hits, so hit counts are capped.",
        "",
        f"- **{len(live_methods)} methods** called live; static census has {len(static_methods)}; "
        f"{len(live_methods - static_methods)} are live-only: "
        + ", ".join(f"`{m}`" for m in sorted(live_methods - static_methods)) + ".",
        f"- Call sites in Fable.exe: **{len(matched)} match** the static census, **{len(new)} are new** "
        f"(static recall on this trace {len(matched) / max(1, len(matched) + len(new)):.0%}).",
        f"- {len(extern)} call sites return into other modules (d3d9.dll state blocks / D3DX), so the "
        "fork's D3D9 shim must also cover device calls the engine makes indirectly.",
        "",
        "## Call sites missing from the static census",
        "",
        "| Method | Call | Function | Hits |",
        "| --- | --- | --- | ---: |",
    ]
    for meth, c, fva, fname, hits in sorted(new, key=lambda r: (r[0], r[1])):
        L.append(f"| `{meth}` | `{c:08X}` | `{fva:08X}` {fname[:70]} | {hits} |")
    L += ["", "## Methods by hits", "", "| Method | Hits | Sites (exe / other) |", "| --- | ---: | --- |"]
    for meth, v in sorted(live["methods"].items(), key=lambda kv: -kv[1]["hits"]):
        ne = sum(1 for r in v["call_sites"] if base <= int(r, 16) < image_end)
        L.append(f"| `{meth}` | {v['hits']} | {ne} / {len(v['call_sites']) - ne} |")
    L.append("")
    OUT_MD.write_text("\n".join(L), encoding="utf-8")
    print(f"{len(live_methods)} methods, {len(matched)} matched, {len(new)} new, {len(extern)} extern")


if __name__ == "__main__":
    main()
