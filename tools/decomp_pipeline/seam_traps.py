#!/usr/bin/env python3
"""Turn a link-closure frontier into named traps, so a seam executable links and runs.

Every unresolved function symbol gets its own tiny extern "C" thunk that reports its
mangled name and exits (code 86); the mangled name is bound to the thunk with
/alternatename. Every unresolved data symbol is bound to its own zero-filled 16 KiB block.
Running the seam then reports the first not-yet-reconstructed callee in real execution
order: the next thing to reconstruct. Traps are scaffolding, never reconstruction.

Usage: python tools/decomp_pipeline/seam_traps.py FRONTIER.txt OUT.cpp
"""
import re
import sys
from pathlib import Path

DATA = re.compile(r"@@[0-9](?:[A-Z]|_[A-Z])")  # MSVC data/variable encodings (@@3..., @@2..., @@0...)

# Members that retail inlines (no retail body of their own) but that the shared
# headers still declare out of line, bound to the retail body they reduce to.
# CAFile is abstract and its ctor/dtor are empty: retail's CDiskFileWin32 ctor
# calls CBaseClassNonCopyable() 0x0099A2F0 and stores its own vptr, and its dtor
# calls ~CBaseClassNonCopyable 0x0099A300 (CDefinitionManager::Compile
# 0x009B08C0, CDefStringTable::LoadTable 0x009D4C30). Remove an entry once the
# header defines the member inline.
INLINE_ALIASES = {
    "??0CAFile@@QAE@XZ": "??0CBaseClassNonCopyable@@QAE@XZ",
    "??1CAFile@@UAE@XZ": "??1CBaseClassNonCopyable@@UAE@XZ",
}


def main():
    frontier = [l.strip() for l in Path(sys.argv[1]).read_text().splitlines() if l.strip()]
    out = ['// GENERATED by tools/decomp_pipeline/seam_traps.py -- scaffolding, not reconstruction.',
           '#include <stdio.h>', '#include <stdlib.h>', '#include <process.h>', '',
           'extern "C" void __cdecl FableSeamTrap(const char* symbol)',
           '{', '    printf("FABLETLC_SEAM_TRAP %s\\n", symbol);', '    fflush(stdout);', '    _exit(86);  // not exit(): static destructors would hit further traps', '}',
           '', 'extern "C" double g_FableSeamDataBlock[2048] = {};', '']
    functions = data = 0
    for i, sym in enumerate(frontier):
        escaped = sym.replace("\\", "\\\\").replace('"', '\\"')
        if sym in INLINE_ALIASES:
            out.append(f'#pragma comment(linker, "/alternatename:{sym}={INLINE_ALIASES[sym]}")')
            continue
        # C-linkage globals carry no type in their name; the repo names them g_*
        # (e.g. _g_FableBankHeaderDirectory_013CA7D4), and a function trap
        # bound to one would be read as data (code bytes, not zeroes).
        if (sym.startswith("?") and DATA.search(sym)) or sym.startswith("_g_"):
            # One zero block per symbol: a shared block turns any counter bump
            # (e.g. a string instance count) into a non-null pointer elsewhere.
            block = f"g_FableSeamData_{i:04d}"
            out.append(f'extern "C" double {block}[2048] = {{}};')
            out.append(f'#pragma comment(linker, "/alternatename:{sym}=_{block}")')
            data += 1
            continue
        name = f"FableSeamTrap_{i:04d}"
        target = sym if sym.startswith("?") else sym  # C symbols already carry their decoration
        out.append(f'extern "C" void __cdecl {name}(void) {{ FableSeamTrap("{escaped}"); }}')
        out.append(f'#pragma comment(linker, "/alternatename:{target}=_{name}")')
        functions += 1
    Path(sys.argv[2]).write_text("\n".join(out) + "\n")
    print(f"{functions} function traps, {data} data blocks -> {sys.argv[2]}")


if __name__ == "__main__":
    main()
