import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;

// Export one reproducible UTF-8 decompile per address. First argument is the output directory.
public class DecompFuncsToDirectory extends GhidraScript {
  @Override public void run() throws Exception {
    String[] args = getScriptArgs();
    if (args.length < 2) {
      throw new IllegalArgumentException("usage: <output-directory> <address> [address ...]");
    }
    File outputDirectory = new File(args[0]);
    Files.createDirectories(outputDirectory.toPath());
    DecompInterface decompiler = new DecompInterface();
    decompiler.setSimplificationStyle("decompile");
    decompiler.openProgram(currentProgram);
    try {
      for (int index = 1; index < args.length; index++) {
        String input = args[index];
        Address address = toAddr(Long.parseLong(input.replace("0x", ""), 16));
        Function function = getFunctionContaining(address);
        if (function == null || !function.getEntryPoint().equals(address)) {
          throw new IllegalStateException("no function entry at " + input);
        }
        DecompileResults result = decompiler.decompileFunction(function, 60, monitor);
        if (result == null || !result.decompileCompleted()) {
          throw new IllegalStateException("decompile failed at " + input + ": " +
              (result == null ? "null result" : result.getErrorMessage()));
        }
        String normalized = String.format("0x%08X", address.getOffset());
        String header = "/* Ghidra project FableTLC/Fable.exe; function entry " + normalized +
            "; generated by DecompFuncsToDirectory.java. */\n\n";
        Files.writeString(new File(outputDirectory, normalized + ".c").toPath(),
            header + result.getDecompiledFunction().getC() + "\n", StandardCharsets.UTF_8);
        println("exported " + normalized);
      }
    } finally {
      decompiler.dispose();
    }
  }
}
